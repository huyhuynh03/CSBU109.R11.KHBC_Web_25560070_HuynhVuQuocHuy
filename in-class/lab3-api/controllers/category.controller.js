// Request handlers for the Category API
const Category = require('../models/category.model');

const SORTABLE_FIELDS = ['name', 'slug', 'createdAt', 'updatedAt'];

// ---------------------------------------------------------------------------
// Reusable input validation middleware
// ---------------------------------------------------------------------------

// POST /api/categories - name is mandatory and must be at least 3 characters
exports.validateCreateCategory = (req, res, next) => {
  const { name } = req.body || {};
  if (typeof name !== 'string' || name.trim().length === 0) {
    return res
      .status(400)
      .json({ success: false, error: 'Category name cannot be empty' });
  }
  if (name.trim().length < 3) {
    return res
      .status(400)
      .json({ success: false, error: 'Category name must be at least 3 characters' });
  }
  next();
};

// PATCH /api/categories/:id - name is optional, but if sent it must be valid
exports.validatePatchCategory = (req, res, next) => {
  const { name } = req.body || {};
  if (name === undefined) return next();
  if (typeof name !== 'string' || name.trim().length === 0) {
    return res
      .status(400)
      .json({ success: false, error: 'Category name cannot be empty' });
  }
  if (name.trim().length < 3) {
    return res
      .status(400)
      .json({ success: false, error: 'Category name must be at least 3 characters' });
  }
  next();
};

// ---------------------------------------------------------------------------
// CRUD handlers
// ---------------------------------------------------------------------------

// 1. GET /api/categories - List categories (pagination & sorting)
exports.getAllCategories = async (req, res, next) => {
  try {
    const page = Math.max(Number(req.query.page) || 1, 1);
    const limit = Math.max(Number(req.query.limit) || 5, 1);

    const sortField = SORTABLE_FIELDS.includes(req.query.sort) ? req.query.sort : 'createdAt';
    const sortOrder = req.query.order === 'asc' ? 1 : -1;

    const skip = (page - 1) * limit;
    const totalCategories = await Category.countDocuments();
    const categories = await Category.find()
      .sort({ [sortField]: sortOrder })
      .skip(skip)
      .limit(limit);

    res.status(200).json({
      success: true,
      count: categories.length,
      pagination: {
        currentPage: page,
        totalPages: Math.ceil(totalCategories / limit),
        totalCategories
      },
      data: categories
    });
  } catch (error) {
    next(error);
  }
};

// 2. GET /api/categories/:id - Get a category by ID
exports.getCategoryById = async (req, res, next) => {
  try {
    const category = await Category.findById(req.params.id);
    if (!category) {
      return res
        .status(404)
        .json({ success: false, error: 'No category found with the given ID' });
    }
    res.status(200).json({ success: true, data: category });
  } catch (error) {
    next(error);
  }
};

// 3. POST /api/categories - Create a category (slug generated by pre('save'))
exports.createCategory = async (req, res, next) => {
  try {
    const { name, description } = req.body;
    const newCategory = await Category.create({ name, description });
    res.status(201).json({
      success: true,
      message: 'Category created successfully',
      data: newCategory
    });
  } catch (error) {
    next(error);
  }
};

// 4. PATCH /api/categories/:id - Partial update (only the fields sent)
// save() hooks do not run on findByIdAndUpdate, so the slug is regenerated here.
exports.updateCategory = async (req, res, next) => {
  try {
    const updates = { ...req.body };

    // Never let the client overwrite the slug directly
    delete updates.slug;

    // Regenerate the slug whenever the name changes
    if (updates.name !== undefined) {
      updates.slug = Category.slugify(updates.name);
    }

    const updatedCategory = await Category.findByIdAndUpdate(
      req.params.id,
      updates,
      { new: true, runValidators: true }
    );

    if (!updatedCategory) {
      return res
        .status(404)
        .json({ success: false, error: 'No category found to update' });
    }

    res.status(200).json({
      success: true,
      message: 'Category updated successfully',
      data: updatedCategory
    });
  } catch (error) {
    next(error);
  }
};

// 5. DELETE /api/categories/:id - Delete a category by ID
exports.deleteCategory = async (req, res, next) => {
  try {
    const deletedCategory = await Category.findByIdAndDelete(req.params.id);
    if (!deletedCategory) {
      return res
        .status(404)
        .json({ success: false, error: 'No category found to delete' });
    }
    res.status(200).json({ success: true, message: 'Category deleted successfully' });
  } catch (error) {
    next(error);
  }
};
